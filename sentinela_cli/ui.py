def _art_size():
    lines = BANNER.split("\n")
    return max(len(l) for l in lines), len(lines)


def _render_art(theme, lines, palette):
    """Pinta as linhas, agrupando runs da mesma cor num unico escape ANSI."""
    for line in lines:
        if not theme.on:
            print(line)
            continue
        out, cur, buf = [], None, []

        def flush():
            if buf:
                code = palette.get(cur)
                if code:
                    out.append(f"\033[{code}m{''.join(buf)}\033[0m")
                else:
                    out.append("".join(buf))
                buf.clear()

        for ch in line:
            kind = ch if ch in palette else None
            if kind != cur:
                flush()
                cur = kind
            buf.append(ch)
        flush()
        print("".join(out))


def show_banner(theme, version="1.0", compact=False):
    """Imprime o banner.

    `compact` (ou terminal pequeno) mostra uma versao curta do logo: a arte
    original tem 111 colunas e nao cabe em 80.
    """
    if not compact:
        term_w = shutil.get_terminal_size((80, 24)).columns
        term_h = shutil.get_terminal_size((80, 24)).lines
        art_w, art_h = _art_size()
        # deixa espaco para o menu (~10 linhas) abaixo
        if art_w > term_w or art_h > term_h - 12:
            compact = True

    if compact:
        _render_art(theme, SHIELD_SMALL, SMALL_PALETTE)
    else:
        _render_art(theme, BANNER.split("\n"), PALETTE)

    print()
    print("  " + theme.bold("S E N T I N E L A") + f"  {theme.dim('v' + version)}")
    print("  " + theme.dim(TAGLINE))
