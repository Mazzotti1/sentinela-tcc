class Theme:
    """Cores ANSI. Desligadas quando a saida nao e um terminal."""

    def __init__(self, enabled=None):
        if enabled is None:
            enabled = sys.stdout.isatty() and os.environ.get("NO_COLOR") is None
        self.on = enabled

    def _w(self, code, text):
        return f"\033[{code}m{text}\033[0m" if self.on else text

    def bold(self, t):
        return self._w("1", t)

    def dim(self, t):
        return self._w("2", t)

    def gold(self, t):
        return self._w("33", t)

    def blue(self, t):
        return self._w("34", t)

    def cyan(self, t):
        return self._w("36", t)

    def green(self, t):
        return self._w("32", t)

    def red(self, t):
        return self._w("31", t)

    def yellow(self, t):
        return self._w("33", t)

    def magenta(self, t):
        return self._w("35", t)

    def inverse(self, t):
        return self._w("7", t)


